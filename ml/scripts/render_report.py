"""Render docs/MODEL_EVALUATION.md and figures from ml/reports/metrics.json.

    python ml/scripts/render_report.py

All numbers in the generated document come from metrics.json; nothing is typed by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
LABEL = {
    "model": "TerraWatch HGB model",
    "model_at_0.5": "HGB model @ 0.5 (pre-registered threshold)",
    "otsu_published": "Published Otsu masks (scene-level, dataset authors)",
    "fixed": "Fixed VV threshold (fit on training events)",
    "otsu": "Per-chip Otsu on VV",
}


def table(block: dict) -> str:
    rows = ["| Method | Precision | Recall | F1 [95% CI] | IoU [95% CI] | Cohen's κ |", "|---|---:|---:|---:|---:|---:|"]
    for k in LABEL:
        if k not in block:
            continue
        m = block[k]
        f, i = m["ci95"].get("f1", [np.nan] * 2), m["ci95"].get("iou", [np.nan] * 2)
        name = f"**{LABEL[k]}**" if k == "model" else LABEL[k]
        rows.append(
            f"| {name} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} [{f[0]:.3f}–{f[1]:.3f}] | "
            f"{m['iou']:.3f} [{i[0]:.3f}–{i[1]:.3f}] | {m['kappa']:.3f} |"
        )
    return "\n".join(rows)


def confusion_png(cm: list[list[int]], title: str, path: Path) -> None:
    a = np.array(cm, dtype=float)
    fig, ax = plt.subplots(figsize=(3.6, 3.2), dpi=150)
    ax.imshow(a / a.sum(), cmap="Blues")
    for (r, c), v in np.ndenumerate(a):
        ax.text(
            c,
            r,
            f"{int(v):,}\n{100 * v / a.sum():.1f}%",
            ha="center",
            va="center",
            fontsize=8,
            color="white" if v / a.sum() > 0.4 else "black",
        )
    ax.set_xticks([0, 1], ["pred. dry", "pred. water"])
    ax.set_yticks([0, 1], ["ref. dry", "ref. water"])
    ax.set_title(title, fontsize=9)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def per_event_png(rows: list[dict], path: Path) -> None:
    ev = [r["event"] for r in rows]
    x = np.arange(len(ev))
    keys = ["model", "otsu_published", "fixed", "otsu"]
    fig, ax = plt.subplots(figsize=(8, 3.2), dpi=150)
    for j, k in enumerate(keys):
        ax.bar(x + (j - 1.5) * 0.2, [r[f"{k}_f1"] for r in rows], 0.2, label=LABEL[k])
    ax.set_xticks(x, ev, rotation=30, ha="right", fontsize=8)
    ax.set_ylabel("F1 (water)")
    ax.set_ylim(0, 1)
    ax.legend(fontsize=7, ncol=2)
    ax.set_title("Leave-one-event-out F1 by held-out event", fontsize=9)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def reliability_png(rel: dict, path: Path) -> None:
    b = rel["bins"]
    fig, ax = plt.subplots(figsize=(3.6, 3.2), dpi=150)
    ax.plot([0, 1], [0, 1], "--", color="grey", lw=0.8)
    ax.plot([r["mean_prob"] for r in b], [r["observed_freq"] for r in b], "o-")
    ax.set_xlabel("predicted P(water)")
    ax.set_ylabel("observed water frequency")
    ax.set_title(f"Reliability (LOEO OOF), ECE={rel['ece']:.3f}", fontsize=9)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main() -> int:
    m = json.loads((ROOT / "ml/reports/metrics.json").read_text())
    fig_dir = ROOT / "docs/figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    confusion_png(m["loeo"]["model"]["confusion_matrix"], "LOEO pooled — model", fig_dir / "cm_loeo.png")
    confusion_png(m["bolivia_holdout"]["model"]["confusion_matrix"], "Bolivia hold-out — model", fig_dir / "cm_bolivia.png")
    per_event_png(m["loeo_per_event"], fig_dir / "f1_per_event.png")
    reliability_png(m["loeo"]["reliability"], fig_dir / "reliability_loeo.png")

    p = m["protocol"]
    pe = "\n".join(
        f"| {r['event']} | {r['chips']} | {r['model_precision']:.3f} | {r['model_recall']:.3f} | **{r['model_f1']:.3f}** | "
        f"{r['otsu_published_f1']:.3f} | {r['fixed_f1']:.3f} | {r['otsu_f1']:.3f} |"
        for r in m["loeo_per_event"]
    )
    imp = "\n".join(f"| `{r['feature']}` | {r['mean']:.4f} ± {r['std']:.4f} |" for r in m["permutation_importance_bolivia"][:10])
    bol, loeo = m["bolivia_holdout"], m["loeo"]
    doc = f"""# Model evaluation

> Generated by `ml/scripts/render_report.py` from `ml/reports/metrics.json` (training run {m["generated_utc"]}).
> Do not edit numbers by hand — re-run `python ml/scripts/train.py && python ml/scripts/render_report.py`.

## Task and data

* **Task:** {m["model"]["task"]}.
* **Dataset:** {m["model"]["dataset"]} — 446 hand-labelled 512×512 chips (10 m) from 11 flood events
  (Bolivia, Ghana, India, Mekong/Cambodia, Nigeria, Pakistan, Paraguay, Somalia, Spain, Sri Lanka, USA), 2016–2019.
  Labels: −1 no data, 0 not water, 1 water (permanent + flood water). Sentinel-1 is GRD IW σ⁰ in dB (VV, VH)
  as pre-processed by Google Earth Engine.
* **Model:** `{m["model"]["classifier"]}` on {len(m["model"]["feature_names"])} per-pixel features
  ({", ".join(f"`{f}`" for f in m["model"]["feature_names"])}),
  {m["model"]["samples_per_chip"]:,} uniformly sampled labelled pixels per chip.
  Hyper-parameters fixed a priori: {", ".join(f"{k}={v}" for k, v in m["model"]["params"].items())}.

## Protocol (leakage control)

1. **Leave-one-event-out (LOEO)** over the {len(p["loeo_events"])} development events: every event is predicted by a model that never
   saw any chip from that event (chips of one event are spatially adjacent and share an acquisition date, so a random chip
   split leaks). Decision threshold {p["threshold_loeo"]}.
2. **Bolivia hold-out:** {", ".join(p["holdout_events"])} is excluded from training, feature/threshold selection and baseline fitting,
   and scored once with the final model trained on all development events.
3. **Official random split:** reported only for comparability with the literature; optimistic because it shares events.

Threshold note: {p["threshold_history"]} The final threshold ({p["threshold_final"]}) was chosen by maximising F1 on pooled
LOEO out-of-fold predictions.

Metrics are computed over all valid labelled pixels; 95% CIs come from 1,000 bootstrap resamples of chips.

## 1. Leave-one-event-out cross-validation (primary)

{table(loeo)}

![F1 per event](figures/f1_per_event.png)

| Held-out event | Chips | Precision | Recall | Model F1 | Published Otsu F1 | Fixed thr. F1 | Per-chip Otsu F1 |
|---|---:|---:|---:|---:|---:|---:|---:|
{pe}

Calibration of out-of-fold probabilities: ECE {loeo["reliability"]["ece"]:.4f}, Brier {loeo["reliability"]["brier"]:.4f}.

<p><img src="figures/cm_loeo.png" width="320"> <img src="figures/reliability_loeo.png" width="320"></p>

## 2. Bolivia out-of-distribution hold-out

{table(bol)}

Calibration on Bolivia: ECE {bol["reliability"]["ece"]:.4f}, Brier {bol["reliability"]["brier"]:.4f}.

<img src="figures/cm_bolivia.png" width="320">

## 3. Official random split (optimistic)

{table(m["official_random_split"]) if m.get("official_random_split") else "_not run_"}

## Permutation importance (Bolivia, ΔF1 when a feature is shuffled)

| Feature | Mean ± sd |
|---|---:|
{imp}

## Interpretation

* In cross-event validation the model has the highest pooled F1 of all methods. The per-chip Otsu baseline is poor because
  many 5 km chips are not bimodal, a known weakness of local thresholding.
* On the Bolivia hold-out, the **published scene-level Otsu masks outperform the model** (F1 {bol["otsu_published"]["f1"]:.3f} vs
  {bol["model"]["f1"]:.3f}). The model keeps high precision ({bol["model"]["precision"]:.3f}) but misses water
  (recall {bol["model"]["recall"]:.3f}) and is under-confident there (ECE {bol["reliability"]["ece"]:.3f} vs
  {loeo["reliability"]["ece"]:.3f} in LOEO).
* The weakest LOEO events are arid scenes, where precision collapses: dry sand and smooth soil are radar-dark like water.

## Known failure modes and limitations

* Flooded vegetation and urban flooding (double-bounce → bright returns) are not captured by a darkness-based model.
* Wind-roughened water, radar shadow in steep terrain, and dry sand produce errors; no DEM/HAND or pre-event image is used.
* One acquisition per event; this is water segmentation, not pre/post change detection. "Inferred flood" in the app
  subtracts JRC permanent water and is not a verified flood map.
* Labels are human interpretations at 10 m and contain their own errors; 11 events cannot represent all climates and sensors.
* Not suitable for operational or safety-critical decisions.

## Optional advanced model (not run in this build)

A U-Net on VV/VH chips (PyTorch) is the natural next step and is commonly reported to beat thresholding on Sen1Floods11.
It was not trained here because of the laptop's disk/compute budget; no results are claimed. The same LOEO + Bolivia
protocol and `terrawatch_ml.metrics` should be reused so results are comparable.
"""
    (ROOT / "docs/MODEL_EVALUATION.md").write_text(doc)
    print("wrote docs/MODEL_EVALUATION.md and docs/figures/*.png")
    return 0


if __name__ == "__main__":
    sys.exit(main())
